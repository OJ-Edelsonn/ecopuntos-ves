package pe.ecopuntosves.web.form;
public class VecinoForm {
    private String dni, nombres, apellidos, direccion, telefono, codigoContribuyente;
    private Integer sectorId;
    public String getDni() { return dni; }
    public void setDni(String x) { dni=x; }
    public String getNombres() { return nombres; }
    public void setNombres(String x) { nombres=x; }
    public String getApellidos() { return apellidos; }
    public void setApellidos(String x) { apellidos=x; }
    public String getDireccion() { return direccion; }
    public void setDireccion(String x) { direccion=x; }
    public String getTelefono() { return telefono; }
    public void setTelefono(String x) { telefono=x; }
    public String getCodigoContribuyente() { return codigoContribuyente; }
    public void setCodigoContribuyente(String x) { codigoContribuyente=x; }
    public Integer getSectorId() { return sectorId; }
    public void setSectorId(Integer x) { sectorId=x; }
}
