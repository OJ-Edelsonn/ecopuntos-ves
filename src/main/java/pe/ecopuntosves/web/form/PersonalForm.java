package pe.ecopuntosves.web.form;
public class PersonalForm {
    private String username, nombres, apellidos, correo, rol;
    public String getUsername() { return username; }
    public void setUsername(String x) { username=x; }
    public String getNombres() { return nombres; }
    public void setNombres(String x) { nombres=x; }
    public String getApellidos() { return apellidos; }
    public void setApellidos(String x) { apellidos=x; }
    public String getCorreo() { return correo; }
    public void setCorreo(String x) { correo=x; }
    public String getRol() { return rol; }
    public void setRol(String x) { rol=x; }
}
